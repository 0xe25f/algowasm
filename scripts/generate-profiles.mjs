// Generates the built-in profile sources from the canonical JSON files in
// `profiles/`, so the Rust engine and the TypeScript package can never drift
// apart. Run with `--check` to fail when the committed output is stale.
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { encodeProfile } from '../packages/algo-wasm/src/profile-wire.ts';

const repoRoot = path.resolve(import.meta.dirname, '..');
const profilesDir = path.join(repoRoot, 'profiles');
const rustTarget = path.join(repoRoot, 'crates/algo-wasm-core/src/builtin.rs');
const tsTarget = path.join(repoRoot, 'packages/algo-wasm/src/built-in-profiles.ts');
const check = process.argv.includes('--check');

// Returns the shortest decimal that reads back as exactly the same f32, so
// the generated Rust stays readable and free of excess-precision warnings.
function formatF32(value) {
  for (let digits = 1; digits <= 9; digits += 1) {
    const text = String(Number(value.toPrecision(digits)));

    if (Math.fround(Number(text)) === value) {
      return /[.e]/.test(text) ? text : `${text}.0`;
    }
  }

  throw new Error(`Could not format ${value} as an f32 literal.`);
}

function camelCase(id) {
  return id.replace(/_([a-z0-9])/g, (_match, letter) => letter.toUpperCase());
}

const fileNames = (await readdir(profilesDir)).filter(name => name.endsWith('.json')).sort();
const profiles = [];

for (const fileName of fileNames) {
  const profile = JSON.parse(await readFile(path.join(profilesDir, fileName), 'utf8'));

  if (fileName !== `${profile.id.replaceAll('_', '-')}.json`) {
    throw new Error(`${fileName} must be named after its profile id, ${profile.id}.`);
  }

  profiles.push(profile);
}

const header = 'Generated by scripts/generate-profiles.mjs from profiles/*.json. Do not edit by hand.';
const rustParts = [
  `//! Built-in profiles in the flat layout read by \`Profile::from_wire\`.`,
  `//!`,
  `//! ${header}`,
  ``,
  `use crate::profile::{Profile, PROFILE_WIRE_LEN};`,
  ``
];

for (const profile of profiles) {
  const name = profile.id.toUpperCase();
  const values = Array.from(encodeProfile(profile), formatF32);
  const lines = [];

  for (let index = 0; index < values.length; index += 8) {
    lines.push(`  ${values.slice(index, index + 8).join(', ')}`);
  }

  rustParts.push(
    `/// Flat layout of the "${profile.displayName}" profile.`,
    `pub const ${name}_WIRE: [f32; PROFILE_WIRE_LEN] = [`,
    lines.join(',\n'),
    `];`,
    ``,
    `/// Returns the built-in "${profile.displayName}" profile.`,
    `pub fn ${profile.id}() -> Profile {`,
    `  decode(&${name}_WIRE)`,
    `}`,
    ``
  );
}

rustParts.push(
  `/// Returns every built-in profile, in file name order.`,
  `pub fn all() -> [Profile; ${profiles.length}] {`,
  `  [${profiles.map(profile => `${profile.id}()`).join(', ')}]`,
  `}`,
  ``,
  `/// Decodes a generated layout. The generator only writes valid profiles, and`,
  `/// the \`built_in_profiles_validate\` test confirms it, so a failure here can`,
  `/// only mean the generated file was edited by hand.`,
  `fn decode(wire: &[f32; PROFILE_WIRE_LEN]) -> Profile {`,
  `  match Profile::from_wire(wire) {`,
  `    Ok(profile) => profile,`,
  `    Err(error) => unreachable!("{}", error.message())`,
  `  }`,
  `}`,
  ``
);

const tsParts = [
  `// ${header}`,
  `import type { AlgoWasmProfile } from './types.js';`,
  ``,
  `/** Identifiers of the built-in profiles, as used by \`builtInProfiles\`. */`,
  `export type BuiltInProfileName = ${profiles.map(profile => `'${camelCase(profile.id)}'`).join(' | ')};`,
  ``,
  `/** The built-in profiles. Clone before use; \`builtInProfiles\` does this for you. */`,
  `export const builtInProfileData: Record<BuiltInProfileName, AlgoWasmProfile> = {`,
  profiles
    .map(profile => {
      const body = JSON.stringify(profile, null, 2).replace(/\n/g, '\n  ');
      return `  ${camelCase(profile.id)}: ${body}`;
    })
    .join(',\n'),
  `};`,
  ``
];

const outputs = [
  [rustTarget, rustParts.join('\n')],
  [tsTarget, tsParts.join('\n')]
];
let stale = false;

for (const [target, contents] of outputs) {
  if (check) {
    const current = await readFile(target, 'utf8').catch(() => '');

    if (current !== contents) {
      console.error(`${path.relative(repoRoot, target)} is out of date. Run npm run generate:profiles.`);
      stale = true;
    }
  } else {
    await writeFile(target, contents);
    console.log(`Wrote ${path.relative(repoRoot, target)}`);
  }
}

if (stale) {
  process.exit(1);
}
